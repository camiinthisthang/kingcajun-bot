import {readFileSync,writeFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
const source=readFileSync(new URL('../onto/king-cajun/delivery.onto',import.meta.url),'utf8');
const revision=createHash('sha256').update(source).digest('hex');
const output=`// Generated by scripts/sync-delivery-model.mjs. Edit onto/king-cajun/delivery.onto.\nexport const source=${JSON.stringify(source)};\nexport const revision=${JSON.stringify(revision)};\n`;
const target=new URL('../admin-dashboard/src/scheduled-model.mjs',import.meta.url);
if(process.argv.includes('--check')){if(readFileSync(target,'utf8')!==output)throw Error('Packaged Onto model is out of date.');}
else writeFileSync(target,output);
